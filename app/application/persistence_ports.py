from __future__ import annotations

from collections.abc import Callable
from datetime import datetime
from typing import Any, Protocol

from app.domain.portfolios import (
    PortfolioCollectionRecord,
    PortfolioDeletedPageRecord,
    PortfolioExportRecord,
    PortfolioSimulationResultRecord,
)


class CacheServicePort(Protocol):
    def get(self, key: str) -> Any | None: ...
    def set(self, key: str, value: Any, ttl: int = 300) -> bool: ...
    def delete_prefix(self, prefix: str) -> int: ...
    async def aget(self, key: str) -> Any | None: ...
    async def aset(self, key: str, value: Any, ttl: int = 300) -> bool: ...
    async def adelete_prefix(self, prefix: str) -> int: ...


class KlineStorePort(Protocol):
    def get_before(self, symbol: str, timeframe: str, end_ts: int, limit: int) -> list[list[float]]: ...
    def get_after(self, symbol: str, timeframe: str, start_ts: int, limit: int) -> list[list[float]]: ...
    def get_range(self, symbol: str, timeframe: str, start_ts: int, end_ts: int) -> list[list[float]]: ...
    def get_latest(self, symbol: str, timeframe: str, limit: int) -> list[list[float]]: ...
    def save(self, symbol: str, timeframe: str, rows: list[list[float]]) -> None: ...


class IndicatorRepositoryPort(Protocol):
    def list_active_meta(self, category: str | None = None) -> list[dict[str, Any]]: ...
    def get_history_points(
        self,
        indicator_ids: list[str],
        *,
        start_date: datetime | None = None,
    ) -> dict[str, list[dict[str, Any]]]: ...
    def upsert_points(self, data_points: list[dict[str, Any]], meta_catalog: dict[str, tuple[str, str, str]]) -> None: ...
    def get_latest_timestamps(self, indicator_ids: list[str]) -> dict[str, datetime]: ...


class BinanceMarketResearchStorePort(Protocol):
    def save_items(self, **kwargs: Any) -> int: ...
    def list_items(self, **kwargs: Any) -> list[dict[str, Any]]: ...


class SentimentRepositoryPort(Protocol):
    def get_latest_date(self) -> datetime | None: ...
    def save_missing(self, records: list[Any]) -> int: ...
    def list_history(self, start_date: datetime | None, end_date: datetime | None) -> dict[str, int]: ...
    def get_latest_index(self) -> dict[str, int | str] | None: ...


DataRetentionCleanup = Callable[[], Any]


class PortfolioRepositoryPort(Protocol):
    def get_collection(self) -> PortfolioCollectionRecord: ...
    def list_deleted(self, *, offset: int, limit: int) -> PortfolioDeletedPageRecord: ...
    def get_simulation(self, portfolio_id: str) -> PortfolioSimulationResultRecord: ...
    def save_simulation(
        self,
        portfolio_id: str,
        expected_revision: int,
        result_payload: dict[str, Any],
    ) -> PortfolioSimulationResultRecord: ...
    def get_export_record(self) -> PortfolioExportRecord: ...
    def apply_collection_changes(
        self,
        active_portfolio_id: str,
        changed_portfolio_payloads: list[dict[str, Any]],
        portfolio_order: list[str],
        expected_revision: int,
    ) -> PortfolioCollectionRecord: ...
    def restore_portfolio(
        self,
        portfolio_id: str,
        expected_revision: int,
    ) -> PortfolioCollectionRecord: ...
    def get_ledger_record(self, portfolio_id: str) -> dict[str, Any]: ...
    def create_transaction(self, portfolio_id: str, payload: dict[str, Any]) -> dict[str, Any]: ...
    def update_transaction(
        self,
        portfolio_id: str,
        transaction_id: str,
        expected_version: int,
        payload: dict[str, Any],
    ) -> dict[str, Any]: ...
    def set_transaction_archived(
        self,
        portfolio_id: str,
        transaction_id: str,
        expected_version: int,
        archived: bool,
    ) -> dict[str, Any]: ...
    def import_transactions(
        self,
        portfolio_id: str,
        payloads: list[dict[str, Any]],
        *,
        replace: bool,
    ) -> tuple[int, int]: ...


