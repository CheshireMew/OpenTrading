from __future__ import annotations

from functools import lru_cache
import re

from sqlalchemy.engine import Connection, Result, Row

from app.infra.persistence.market.history.catalog_schema import SCHEMA_SQL


TABLES = tuple(re.findall(r"CREATE TABLE IF NOT EXISTS (\w+)", SCHEMA_SQL))
_INDEXES = tuple(re.findall(r"CREATE (?:UNIQUE )?INDEX IF NOT EXISTS (\w+)", SCHEMA_SQL))
_IDENTIFIERS = re.compile(
    r"'(?:[^']|'')*'|\b(?:" + "|".join((*TABLES, *_INDEXES)) + r")\b",
)
_WRITE_LOCK = 983760412
_NAMED_TABLES = frozenset(f"signal_lab_{name}" for name in TABLES)


def owns_table(name: str) -> bool:
    return name in _NAMED_TABLES


def _namespaced(match: re.Match) -> str:
    value = match[0]
    return value if value.startswith("'") else f"signal_lab_{value}"


@lru_cache(maxsize=512)
def catalog_sql(statement: str, postgres: bool) -> str:
    output = _IDENTIFIERS.sub(_namespaced, statement)
    if postgres:
        # Repository SQL uses qmark placeholders and avoids literal question marks.
        output = output.replace("%", "%%").replace("?", "%s")
    return output


def schema_statements(postgres: bool):
    for source in SCHEMA_SQL.split(";"):
        statement = source.strip()
        if not statement or statement.startswith("DROP INDEX"):
            continue
        if postgres:
            statement = re.sub(r"\bREAL\b", "DOUBLE PRECISION", statement)
            statement = statement.replace(
                "INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            )
        yield catalog_sql(statement, postgres)


class CatalogRow:
    def __init__(self, row: Row) -> None:
        self._row = row

    def keys(self):
        return self._row._mapping.keys()

    def __getitem__(self, key):
        return self._row._mapping[key] if isinstance(key, str) else self._row[key]

    def __iter__(self):
        return iter(self._row)

    def __len__(self) -> int:
        return len(self._row)


class CatalogResult:
    def __init__(self, result: Result) -> None:
        self._result = result

    @property
    def rowcount(self) -> int:
        return self._result.rowcount

    def fetchone(self) -> CatalogRow | None:
        row = self._result.fetchone()
        return CatalogRow(row) if row is not None else None

    def fetchall(self) -> list[CatalogRow]:
        return [CatalogRow(row) for row in self._result.fetchall()]


class CatalogConnection:
    def __init__(self, connection: Connection) -> None:
        if connection.dialect.name not in {"postgresql", "sqlite"}:
            raise ValueError("Signal Lab requires a PostgreSQL or SQLite OpenTrading database")
        self._connection = connection
        self._postgres = connection.dialect.name == "postgresql"
        self._write_locked = False

    def execute(self, statement: str, parameters=()) -> CatalogResult | None:
        command = statement.lstrip().split(maxsplit=1)[0].upper()
        if statement.strip().upper() == "BEGIN IMMEDIATE":
            self._lock_for_write()
            return None
        if statement.strip().upper() == "BEGIN":
            sql = "SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY" if self._postgres else "BEGIN"
            self._connection.exec_driver_sql(sql)
            return None
        if command in {"INSERT", "UPDATE", "DELETE"}:
            self._lock_for_write()
        sql = catalog_sql(statement, self._postgres)
        return CatalogResult(self._connection.exec_driver_sql(sql, tuple(parameters)))

    def executemany(self, statement: str, parameters) -> None:
        rows = [tuple(row) for row in parameters]
        if not rows:
            return
        self._lock_for_write()
        sql = catalog_sql(statement, self._postgres)
        self._connection.exec_driver_sql(sql, rows)

    def size_bytes(self) -> int | None:
        if self._postgres:
            return self._connection.exec_driver_sql("SELECT pg_database_size(current_database())").scalar_one()
        pages = self._connection.exec_driver_sql("PRAGMA page_count").scalar_one()
        size = self._connection.exec_driver_sql("PRAGMA page_size").scalar_one()
        return pages * size

    def sync_event_sequence(self) -> None:
        if self._postgres:
            self._connection.exec_driver_sql("""
                SELECT setval(
                    pg_get_serial_sequence('signal_lab_operation_events', 'event_id'),
                    COALESCE(MAX(event_id), 1), COUNT(*) > 0
                )
                FROM signal_lab_operation_events
            """)

    def _lock_for_write(self) -> None:
        if self._write_locked:
            return
        if self._postgres:
            self._connection.exec_driver_sql("SELECT pg_advisory_xact_lock(%s)", (_WRITE_LOCK,))
        else:
            self._connection.exec_driver_sql("BEGIN IMMEDIATE")
        self._write_locked = True
