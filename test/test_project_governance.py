def test_declared_runtime_versions_and_lockfiles_remain_in_sync():
    root_package = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))
    frontend_package = json.loads((ROOT / "frontend" / "package.json").read_text(encoding="utf-8"))
    python_version = (ROOT / ".python-version").read_text(encoding="utf-8").strip()
    lock_text = (ROOT / "pdm.lock").read_text(encoding="utf-8")
    requirements_lock = (ROOT / "requirements.lock").read_text(encoding="utf-8")
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]

    assert project["version"] == APP_VERSION
    assert root_package["version"] == APP_VERSION
    assert frontend_package["version"] == APP_VERSION
    assert root_package["engines"]["node"] == ">=22.12.0"
    assert frontend_package["engines"]["node"] == ">=22.12.0"
    assert python_version == "3.12.10"
    assert 'platform = "windows_amd64"' in lock_text
    assert 'requires_python = "==3.12.*"' in lock_text
    assert requirements_lock.startswith("# This file is @generated by PDM.")
    assert "--hash=sha256:" in requirements_lock


